// Native Kogger sonar renderer integration contracts; hardware-free CI smoke.
import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const sonar=read('custom/qml/NavoSonarPro.qml');
const source=read('custom/qml/NavoSonarEthernet.qml');
const renderer=read('custom/src/NavoKoggerEchogramItem.cc');
const header=read('custom/src/NavoKoggerEchogramItem.h');
const cmake=read('custom/CMakeLists.txt');
const plugin=read('custom/src/CustomPlugin.cc');
const palette=read('custom/kogger_native/navo_kogger_echogram_palette.h');
const sampling=read('custom/kogger_native/navo_kogger_echogram_sampling.h');
const required=(content,needle,msg)=>assert(content.includes(needle),msg||needle);

required(sonar,'property bool useNativeRenderer: true','new native Kogger renderer is not the default');
required(sonar,'NavoKoggerEchogramItem {','new Qt native renderer missing from page');
required(sonar,'objectName:"sonarProNativeKoggerEchogram"');
required(sonar,'visible:!root.useNativeRenderer','old 4-bin fallback must remain reversible');
required(sonar,'decoder:root.chartSource ? (root.chartSource.nativeEchogramDecoder || null) : null');
required(source,'property alias nativeEchogramDecoder: decoderObject');
required(sonar,'nativeEchogram.setBottomDepth(sequence,depth)');
required(sonar,'nativeEchogram.resetColumns();inspectedColumn=({})');
required(sonar,'nativeEchogram.inspectAt(mouse.x,mouse.y)','native inspection tap must use same exact column');
required(sonar,'text:root.useNativeRenderer ? "Motor: Kogger nativ 256 niveluri"');
required(renderer,'connect(_decoder,&NavoKoggerDecoder::chartColumnReady','exact completed CHART trigger required');
required(renderer,'c.bytes=_decoder->chartRawBytes()','must retain raw 8-bit source (not QML bins)');
required(renderer,'image.setColorTable(NavoKoggerPalette::colors(');
required(renderer,'QImage::Format_Indexed8','renderer still uses low-resolution rectangles');
required(renderer,'NavoKoggerSampling::atDisplayDepth(');
required(renderer,'_frameTimer.setInterval(33)','paint calls must be throttled for G20');
required(renderer,'while(_columns.size()>MaxRetainedColumns || _rawCacheBytes>MaxRawCacheBytes)','G20 size/byte cache evictions missing');
required(header,'MaxRetainedColumns=4096');
required(header,'MaxRawCacheBytes=24*1024*1024');
required(renderer,'_rawCacheBytes>MaxRawCacheBytes');
required(renderer,'QMutexLocker lock(&_mutex)','cross-thread native snapshots must be protected');
assert(!/sendCommand\(|MAV_CMD|guidedModeGotoLocation\(|uploadMission\(/.test(renderer),'renderer contains navigation or control code');
required(palette,'src/scene2d/plot2D_echogram.cpp (GPL-3.0)');
required(sampling,'src/epoch.h (GPL-3.0)');
assert(palette.includes('QVector<QRgb> adjusted(256)'),'8-bit color table not mapped');
assert(!renderer.includes('Uint8Array') && renderer.includes('image.scanLine(y)[x]=quint8(value);'),'raster amplitude is not written as exact 8-bit pixels');
required(cmake,'src/NavoKoggerEchogramItem.cc');
required(plugin,'qmlRegisterType<NavoKoggerEchogramItem>');
const mock=read('tests/kogger-replay/mock-imports/NavoSmart/Backend/qmldir');
required(mock,'NavoKoggerEchogramItem 1.0');
console.log('PASS native Kogger input isolation, 256-color image, bounded G20 snapshots, Qt registration, native touch inspection, reversible fallback');
